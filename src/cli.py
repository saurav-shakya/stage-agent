"""Command line entry point.

    python -m src.cli run    [--pack data_pack/one_user_one_agent_pack] --out sample_run
    python -m src.cli viewer U-01991 --out sample_run [--at 2026-10-01T10:00:00Z]
"""
import argparse
import json
import os
import subprocess
import sys
from collections import Counter

from . import impact, reports
from .agent import Config
from .judge import judge_all, load_outcome_events
from .pack import PackNotFound, find_pack
from .replay import read_jsonl, run_replay
from .store import Store
from .timeutil import ist_day, ts


def cmd_run(a):
    try:
        pack = find_pack(a.pack)
    except PackNotFound as e:
        sys.exit('error: %s' % e)
    out = a.out
    cfg = Config(model_timeout_ms=a.model_timeout_ms, max_model_calls=a.max_model_calls,
                 max_tool_calls=a.max_tool_calls, messages_enabled=not a.no_messages)
    rt = run_replay(pack, out, workers=a.workers, config=cfg)
    sim_dir = os.path.join(out, 'sim')
    print('running simulator (seed %s)...' % a.seed)
    subprocess.run([sys.executable, '-I', os.path.join(pack, 'simulator/simulate_outcomes.py'), '--pack', pack,
                    '--actions', os.path.join(out, 'actions.jsonl'), '--out', sim_dir, '--seed', a.seed], check=True)
    outcomes, horizon = judge_all(rt, sim_dir)
    reports.write_outcomes(out, outcomes)
    n = reports.write_viewer_state(rt, out)
    decisions = rt.store.all_decisions()
    controls = read_jsonl(os.path.join(pack, 'replay/control_events.jsonl'))
    lat = reports.latency_report(decisions, controls, cfg.latency_budget_ms)
    with open(os.path.join(out, 'latency_report.json'), 'w') as f:
        json.dump(lat, f, indent=2)
    sim_report = json.load(open(os.path.join(sim_dir, 'simulator_report.json')))
    imp = impact.compute(rt, load_outcome_events(sim_dir), outcomes)
    pil = impact.pilot(pack)
    with open(os.path.join(out, 'impact_report.md'), 'w', encoding='utf-8') as f:
        f.write(reports.impact_report(imp, pil, sim_report))
    with open(os.path.join(out, 'final_report.md'), 'w', encoding='utf-8') as f:
        f.write(final_report(rt, decisions, outcomes, lat, imp, sim_report))
    with open(os.path.join(out, 'run_summary.json'), 'w') as f:
        json.dump({'impact': imp, 'pilot': {k: v for k, v in pil.items() if k != 'goal_mix'}}, f, indent=2, default=str)
    rt.store.close()
    print('wrote %d viewer states, %d outcomes; reports in %s' % (n, len(outcomes), out))


def final_report(rt, decisions, outcomes, lat, imp, sim):
    st = rt.store
    L = []
    w = L.append
    days = sorted({ist_day(ts(d['trigger']['received_at'])) for d in decisions})
    span = (days[0] if days[0] == days[-1] else '%s to %s' % (days[0], days[-1])) if days else 'no triggers'
    w('# Final report: replay of %s (IST)\n' % span)
    w('Generated by `python -m src.cli run`. Narrative and design reasoning are in ARCHITECTURE.md; this file is '
      'the factual record of the run.\n')
    w('## Decisions\n')
    w('| Status | Reason | Count |')
    w('|---|---|---|')
    for (s, r), c in sorted(Counter((d['status'], (d['no_action_reason'] or '').split(':')[0] if d['status'] ==
                                     'NO_ACTION' else '') for d in decisions).items(), key=lambda x: -x[1]):
        w('| %s | %s | %d |' % (s, r or '-', c))
    pub = [d for d in decisions if d['status'] == 'PUBLISHED']
    w('\nActions published: %s.' % ', '.join('%s %d' % kv for kv in Counter(d['action'] for d in pub).items()))
    w('Goals chosen (agent arm, new commitments): %s.' % ', '.join(
        '%s %d' % kv for kv in sorted(Counter(d['goal']['id'] for d in decisions
                                              if d['goal'] and not d['goal']['carried_over'] and d['arm'] == 'agent').items())))
    w('Goals never chosen by design: G10 (no success signal), G11 (success event does not exist).\n')
    fails = Counter()
    for d in decisions:
        for x in d['checks']['failed']:
            fails[x.split(':')[0] + (':' + x.split(':')[1].strip() if x.startswith(('page:', 'message:')) else '')] += 1
    w('Verifier rejections (component removed or decision stopped): %s.\n' % (
        ', '.join('%s %d' % kv for kv in fails.most_common()) or 'none'))
    w('## Outcomes\n')
    oc = Counter((o['arm'], o['status']) for o in outcomes)
    w('| Arm | succeeded | failed | inconclusive |')
    w('|---|---|---|---|')
    for arm in ('agent', 'holdout'):
        w('| %s | %d | %d | %d |' % (arm, oc[(arm, 'succeeded')], oc[(arm, 'failed')], oc[(arm, 'inconclusive')]))
    att = Counter(o['attribution'] for o in outcomes if o['arm'] == 'agent' and o['status'] == 'succeeded')
    w('\nAgent-arm successes by attribution: %s.\n' % ', '.join('%s %d' % kv for kv in att.items()))
    w('## Surprises and how the run handled them\n')
    for j in st.journal_kind('control_event'):
        w('- **%s %s**: %s' % (j['at'], j['type'], j.get('detail') or j.get('reason') or j.get('note') or ''))
    for j in st.journal_kind('title_withdrawn_impact'):
        w('  - affected only viewers holding %s: %d pages republished without it, %d left without replacement, '
          '%d messages cancelled.' % (j['title_id'], j['pages_republished'], j['pages_left_without_replacement'],
                                      j['messages_cancelled']))
    for j in st.journal_kind('goal_rule_correction_impact'):
        w('  - %s v%d: %d open goals re-pointed to the corrected rule (%d viewers); no other viewer reprocessed.'
          % (j['goal_id'], j['version'], j['open_goals_updated'], j['viewers_touched']))
        if j.get('measurable') is False:
            w('  - %s v%d cannot be judged (%s): its goals are reported inconclusive, not guessed, and no new viewer '
              'was committed to %s after the correction.' % (j['goal_id'], j['version'], j['measurable_reason'],
                                                            j['goal_id']))
    mo = lat.get('model_outcomes', {})
    w('  - model calls: %s. Every non-ok outcome fell back to the rule-based goal; no decision waited longer than '
      'the model timeout (%d ms), and after a 503 or %d timeouts in a row the circuit skipped the model for %d s.'
      % (', '.join('%s %d' % kv for kv in mo.items()), rt.model.timeout_ms,
         rt.model.BREAKER_AFTER_TIMEOUTS, rt.model.BREAKER_S))
    by = lat['by_condition']
    for k, v in by.items():
        if k != 'normal':
            w('  - during %s: %d decisions, p95 %d ms, max %d ms.' % (k, v['n'], v['p95_ms'], v['max_ms']))
    stale = sum(1 for d in decisions if (d['no_action_reason'] or '').startswith('stale_trigger'))
    w('- **Offline-buffered app opens**: %d triggers held on the phone > 10 min were recorded as NO_ACTION '
      '(stale_trigger) and used only as history.' % stale)
    rp = st.journal_kind('replan_purchase')
    w('- **Purchases arriving after a decision**: %d live purchases updated the subscription fact over the '
      'snapshot; %d open purchase goals closed; %d pending messages cancelled.' % (
          len(rp), sum(1 for j in rp if j.get('goal_closed')), sum(j.get('messages_cancelled', 0) for j in rp)))
    three = sum(1 for d in decisions if d.get('dialect') and len(d['dialect']['conflicts']) >= 2)
    w('- **Three-way dialect conflicts** (app setting, profile, campaign link): %d decisions; the page always used '
      'the app setting and listed the other two as conflicts.' % three)
    claims = [d for d in decisions if any(x.startswith('model_claim') for x in d['checks']['failed'])]
    w('- **Unsupported model claims rejected**: %d (%s).' % (len(claims), ', '.join(d['viewer_id'] for d in claims)))
    inj = [t for t, v in rt.pack.titles.items() if v['injection_flag']]
    w('- **Instruction text inside the catalogue**: flagged on %s. Descriptions are never sent to the model and '
      'never drive actions; total messages sent in the run: %d, all through the verifier.' % (
          ', '.join(inj), sum(1 for d in decisions for a in d.get('message_schedule', []))))
    for label, key in (('Evening peak', 'evening_peak'), ('Busiest 10 minutes of the day', 'busiest_10min')):
        pk = lat[key]
        w('- **%s**: %s IST, %d triggers (%.1fx the median 10 minutes); p95 publish delay %s ms, max %s ms, '
          'mean queue wait %s ms.' % (label, pk['bucket_ist'], pk['triggers'], pk['x_median'], pk.get('p95_ms'),
                                      pk.get('max_ms'), pk.get('mean_queue_wait_ms')))
    w('\n## Latency\n')
    a = lat['all_decisions']
    w('p50 %d ms, p95 %d ms, max %d ms; %d decisions over 60 s, %d over 5 min.\n' % (
        a['p50_ms'], a['p95_ms'], a['max_ms'], a['over_60s'], a['over_5min']))
    w('## Impact (headline)\n')
    r = imp['itt'][1]
    w('ITT, %s: agent %s vs holdout %s, difference %+.2f pts (95%% CI ±%.2f). Full table and the pilot re-analysis '
      'are in impact_report.md. Simulator policy problems: %d.\n' % (
          r['metric'], pct(r['agent_rate']), pct(r['holdout_rate']), r['diff_pts'], r['ci95_pts'],
          sim.get('policy_problem_count', 0)))
    return '\n'.join(L) + '\n'


def pct(x):
    return '%.2f%%' % (100 * x)


def cmd_viewer(a):
    st = Store(os.path.join(a.out, 'state.sqlite'))
    at = a.at
    keep = (lambda t: t is None or at is None or t <= at)
    print('== viewer %s%s' % (a.user, ' as of %s' % at if at else ''))
    print('\n-- facts known at each decision (key, value, source, ref, age_s, conflicts)')
    for r in st.facts_for(a.user):
        if keep(r['recorded_at']):
            print('%s %-22s %-28s %-18s %-48s %s %s' % (r['decision_id'], r['key'], r['value'][:28], r['source'],
                                                         (r['ref'] or '')[:48], r['age_s'], r['conflicts']))
    print('\n-- decisions')
    for d in st.decisions_for(a.user):
        if keep(d['trigger']['deliver_at']):
            print(json.dumps({k: d.get(k) for k in ('decision_id', 'status', 'action', 'no_action_reason', 'goal',
                                                     'dialect', 'confidence', 'confidence_reason', 'checks',
                                                     'publish_delay_ms')}, indent=1))
    print('\n-- actions')
    for x in st.actions_for(a.user):
        if keep(x['published_at']):
            print(x['action_id'], x['type'], x['status'], x['published_at'], x['send_at'] or '', x['title_ids'])
    print('\n-- journal')
    for j in st.journal_for(a.user):
        if keep(j['at']):
            print(j['at'], j['kind'], json.dumps({k: v for k, v in j.items() if k not in ('at', 'kind')})[:200])
    if at is None:
        print('\n-- outcomes')
        for o in st.outcomes():
            if o['user_id'] == a.user:
                print(json.dumps(o, indent=1))


def main(argv=None):
    p = argparse.ArgumentParser(prog='python -m src.cli')
    sub = p.add_subparsers(dest='cmd', required=True)
    r = sub.add_parser('run', help='replay the trigger script, simulate outcomes, judge goals, write reports')
    r.add_argument('--pack', default=None,
                   help='pack directory (default: $OUA_PACK, else data_pack/one_user_one_agent_pack or data_pack)')
    r.add_argument('--out', default='sample_run')
    r.add_argument('--seed', default='oua-practice')
    r.add_argument('--workers', type=int, default=4)
    r.add_argument('--model-timeout-ms', type=int, default=2500)
    r.add_argument('--max-model-calls', type=int, default=8)
    r.add_argument('--max-tool-calls', type=int, default=20)
    r.add_argument('--no-messages', action='store_true', help='home page only, no push / WhatsApp')
    r.set_defaults(fn=cmd_run)
    v = sub.add_parser('viewer', help='show what the agent knew, decided and observed for one viewer')
    v.add_argument('user')
    v.add_argument('--out', default='sample_run')
    v.add_argument('--at', default=None, help='ISO time; show state as of this moment')
    v.set_defaults(fn=cmd_viewer)
    a = p.parse_args(argv)
    a.fn(a)


if __name__ == '__main__':
    main()
